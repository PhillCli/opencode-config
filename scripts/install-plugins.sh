#!/usr/bin/env bash

# OpenCode V2's global plugin loader fails on symlinked entrypoints
# (anomalyco/opencode#23553), so versioned plugins in plugins/ are
# materialized as real one-line re-export shims in the global plugins
# directory instead of being symlinked like skills/ or commands/.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(dirname "$SCRIPT_DIR")"
SRC_DIR="$REPO_ROOT/plugins"
DEST_DIR="$HOME/.config/opencode/plugins"
MARKER="# generated by scripts/install-plugins.sh (anomalyco/opencode#23553)"

mkdir -p "$DEST_DIR"

shim() {
  printf '%s\nexport { default } from "%s"\n' "$MARKER" "$1"
}

# Install or refresh a shim for every versioned plugin. Compare first so an
# unchanged shim is not rewritten and the plugin dir watcher stays quiet.
for src in "$SRC_DIR"/*.ts; do
  [[ -e "$src" ]] || continue
  dest="$DEST_DIR/$(basename "$src")"
  if ! cmp -s <(shim "$src") "$dest"; then
    shim "$src" > "$dest"
  fi
done

# Remove stale generated shims whose source plugin is gone.
for dest in "$DEST_DIR"/*.ts; do
  [[ -f "$dest" ]] || continue
  grep -qF "$MARKER" "$dest" || continue
  [[ -e "$SRC_DIR/$(basename "$dest")" ]] || rm "$dest"
done
